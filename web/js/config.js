// Конфигурация фронтенда: единственное место, где страница знает, где живёт API.
//
// Зачем это нужно: макет раздаётся либо тем же Go-сервером (вариант A в
// docs/02 §9), и тогда пути относительные/same-origin, либо GitHub Pages с
// внешним бэкендом (вариант B), и тогда у API другой origin. Разница целиком
// закрывается этим файлом — код страниц про неё не знает.
//
// Значения по умолчанию рассчитаны на вариант A: `API_BASE_URL` пустой, запрос
// уходит на тот же источник, cookie отправляются как same-origin. Для варианта B
// достаточно выставить базовый URL (без завершающего слэша) — api-client
// переключит `credentials` на `include`, а сервер должен отдать CORS-заголовки
// с этим origin и `SameSite=None; Secure` для cookie. Без CORS вход работать не
// будет: это ограничение браузера, а не нашего кода.
//
// Значения можно задать и из HTML, не редактируя файл:
//   <script src="/js/config.js" data-api-base-url="https://api.example.test"></script>
window.SOS_CONFIG = (function () {
    "use strict";

    // Атрибуты script читаем через document.currentScript: он указывает именно
    // на этот тег, пока он исполняется.
    const tag = document.currentScript;
    const fromAttribute = tag && tag.dataset ? tag.dataset.apiBaseUrl : "";

    return {
        // "" = тот же источник, что и страница.
        API_BASE_URL: fromAttribute || "",

        // Пути страниц — относительные ("login", а не "/login") и без ведущего
        // слэша. Причина ровно та же, что у src="js/...": при варианте B страницы
        // лежат под каталогом GitHub Pages (https://user.github.io/SOS/login), и
        // абсолютный "/login" увёл бы браузер в корень домена, где ничего нет.
        // Относительный путь браузер разрешает от текущей страницы и в том, и в
        // другом случае. Ссылки в HTML (href) идут этому же правилу.
        LOGIN_PATH: "login",

        // Главная — не "index.html": Go-сервер отдаёт её по "/" и корневой
        // адрес страницы выглядит "./".
        HOME_PATH: "./",

        // Личный кабинет — сюда ведут «войти» и «не туда пошёл» (не-админ на /admin).
        DASHBOARD_PATH: "dashboard",

        // Путь разрыва сеанса: после «выйти везде» account.js сам решает, куда
        // идти, здесь только точка по умолчанию.
        SESSION_REVOKED_PATH: "login?revoked=1",

        // Точка входа для таймаута запроса: дольше ждать смысла нет — сервер
        // режет сам (docs/02 §7), а «вечный spinner» хуже явной ошибки.
        REQUEST_TIMEOUT_MS: 15000,

        // Переопределяется тестами: в jsdom навигация не реализована, и тест
        // подставляет функцию, чтобы увидеть «куда уводит» без навигации.
        navigateTo: null,
    };
})();
