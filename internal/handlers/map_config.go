package handlers

import (
	"net/http"
	"net/url"
	"strings"
)

// Конфигурация карты (GET /api/map/config).
//
// Адрес тайл-сервера приходит из окружения, а не из JS-файла, по двум причинам.
// Первая — бриф (п.6): интерфейс не имеет права зашивать чужой сервис. Ссылка
// на тайлы, встроенная в репозиторий, превратила бы каждый показ карты в
// запрос на чужой хост и обязала бы переписывать код при смене сервера.
// Вторая — разработчик поднимает свой тайл-сервер строкой в окружении, и ему
// не нужна правка фронтенда.
//
// Второе следствие важнее первой с точки зрения кода: отсутствие тайлов —
// штатное состояние сборки, а не авария. Карта обязана оставаться рабочей и
// без подложки: маркеры, легенда и список мест читаются и на пустом фоне,
// поэтому ответ говорит «тайлов нет» и имя переменной, а не 503.

// MapTiles — конфигурация подложки, собранная в main.go из переменных
// MAP_TILES_URL и MAP_TILES_ATTRIBUTION.
type MapTiles struct {
	// URL — шаблон тайлов в форме Leaflet (`…/{z}/{x}/{y}.png`). Пустой —
	// подложки нет.
	URL string

	// Attribution — строка происхождения, которую тайл-сервер просит показывать.
	// Пустая — показывать нечего: подставить «условный правообладатель» значит
	// соврать про источник, поэтому поле либо слова оператора, либо пусто.
	Attribution string
}

// Problem — имя переменной окружения, из-за которой подложку нельзя отдать
// браузеру, и подсказка оператору. Пустое первое значение значит, что
// конфигурация годится.
//
// Два текста у одного решения не дублирование, а два разных адресата: браузеру
// достаточно имени переменной (понять, что подложки нет и карта пустая не по
// вине сервера), а в лог запуска должна уйти формулировка, по которой
// администратор найдёт, что именно он написал не так. Тот же разделитель, что у
// ScheduleSourceMissing: имя — клиенту, текст — оператору.
//
// Правила отбора — не придирчивость, а защита от двух состояний, которые
// выглядят как «карта сломалась по вине сервера»:
//
//   - без `{…}`-шаблона Leaflet запрашивал бы один и тот же файл на каждую
//     плитку, и карта была бы серой сеткой из копий;
//   - `user:token@host` в адресе уехал бы в каждый запрос браузера, то есть
//     секрет оператора попал бы в историю, в кэш прокси и в чужие access-логи.
//     Именно поэтому бриф запрещает токены в URL (п.2).
func (t MapTiles) Problem() (env, hint string) {
	raw := strings.TrimSpace(t.URL)
	if raw == "" {
		return "MAP_TILES_URL", "подложка карты не настроена: задайте MAP_TILES_URL шаблоном " +
			"вида https://тайлы.вуз/{z}/{x}/{y}.png и, если провайдер требует подпись, MAP_TILES_ATTRIBUTION"
	}

	parsed, err := url.Parse(raw)
	// Текст подсказки намеренно не пересказывает значение переменной: адрес
	// тайл-сервера может содержать ключ в query, а лог читают несколько людей.
	// Оператор своё значение видит в окружении, и ему достаточно требования.
	if err != nil {
		return "MAP_TILES_URL", "MAP_TILES_URL не разбирается как адрес"
	}
	if parsed.Host == "" || (parsed.Scheme != "http" && parsed.Scheme != "https") {
		return "MAP_TILES_URL", "MAP_TILES_URL обязан быть абсолютным адресом по http или https"
	}
	// url.Parse разбирает учётные данные отдельно: проверка дешевле собственного
	// разбора адреса и ловит именно ту форму, которую оператор копирует из
	// документации провайдера вместе с ключом.
	if parsed.User != nil {
		return "MAP_TILES_URL", "в MAP_TILES_URL есть учётные данные — адрес уйдёт в каждый запрос " +
			"браузера и попадёт в чужие логи; ключ тайл-сервера должен быть в самом URL без авторизации " +
			"или в заголовках, которые настраивает прокси"
	}

	if !hasTileTemplate(raw) {
		return "MAP_TILES_URL", "в MAP_TILES_URL нет ни одного плейсхолдера Leaflet ({z}, {x}, {y} или TMS/WMS-форма): " +
			"без шаблона каждая плитка запрашивалась бы по одному адресу"
	}

	return "", ""
}

// Origin — `scheme://host` подложки: строка запуска, где полный адрес печатать
// нельзя — в нём может стоять ключ провайдера, а лог читают несколько человек.
// Пустая строка у негодной конфигурации: называть происхождение тайлов, которых
// нет, значило бы врать в логе.
func (t MapTiles) Origin() string {
	if env, _ := t.Problem(); env != "" {
		return ""
	}

	parsed, err := url.Parse(strings.TrimSpace(t.URL))
	if err != nil {
		return ""
	}

	return parsed.Scheme + "://" + parsed.Host
}

// hasTileTemplate — есть ли в адресе хоть один плейсхолдер Leaflet: `{z}`,
// `{x}`, `{y}`, `{s}` или форма TMS/WMS (`{TileMatrix}`, `{bbox-…}`). Проверяется
// именно пара скобок, а не список имён: Leaflet понимает их больше, чем здесь
// перечислено, и запрещать неизвестный нам вариант значило бы ломать рабочую
// конфигурацию оператора.
func hasTileTemplate(raw string) bool {
	open := strings.IndexByte(raw, '{')
	if open < 0 {
		return false
	}

	// Пустые скобки `{}` — не плейсхолдер: Leaflet оставил бы их в адресе как
	// есть, и каждая плитка грузилась бы по одному и тому же пути.
	closing := strings.IndexByte(raw[open+1:], '}')

	return closing > 0
}

// mapConfigResponse — то, что читает страница.
type mapConfigResponse struct {
	// Tiles — подложка или null. Различие «пустая строка» и «нет поля» здесь
	// сознательно слито в null: фронтенд не должен разбирать два вида «нет».
	Tiles *mapTilesView `json:"tiles"`

	// Problem — имя переменной, которую стоит задать. Без тайлов и без этого
	// поля страница показывала бы пустой фон без объяснения.
	Problem string `json:"problem,omitempty"`
}

type mapTilesView struct {
	URL         string `json:"url"`
	Attribution string `json:"attribution"`
}

// MapConfigAPI — GET /api/map/config.
//
// Под право не кладётся: конфиг — две строки, которые сервер всё равно
// отправляет всякому вошедшему, и он ничего не меняет. Публичным путь тоже не
// объявлен: карта адресована вошедшему (страница /map под RequireAuth), и
// гостю незачем узнавать адрес внутреннего тайл-сервера.
func (h *Handlers) MapConfigAPI(w http.ResponseWriter, r *http.Request) {
	if r.Method != http.MethodGet {
		methodNotAllowed(w)
		return
	}

	config := mapConfigResponse{}

	if env, _ := h.MapTiles.Problem(); env == "" {
		config.Tiles = &mapTilesView{
			// Пробелы по краям отрезаны: оператор мог задать строку с
			// переносом, а показывать её в подвале карты в таком виде —
			// значит портить подпись.
			URL:         strings.TrimSpace(h.MapTiles.URL),
			Attribution: strings.TrimSpace(h.MapTiles.Attribution),
		}
	} else {
		config.Problem = env
	}

	writeJSON(w, http.StatusOK, config)
}
