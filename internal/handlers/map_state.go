package handlers

// Словарь состояний точки для обоих слоёв карты.
//
// Одно и то же слово описывает и объект в сводке, и причину в unplaced:
// «почему не показано» — это ровно «в каком состоянии точка», второго словаря
// быть не должно. Фронтенд читает `place_state` из обоих путей и рисует по нему
// легенду, поэтому «unresolved» обязан значить «нет координат» и на паре, и на
// событии.
//
// Подмножества у слоёв разные: у пар точка ищется по корпусу из строки
// аудитории (missing, no_building, several), у событий место выбирает человек
// (no_place) и у события есть своя дата (no_date). `resolved` и `unresolved`
// общие.
const (
	// placeStateResolved — координаты есть, маркер ставим.
	placeStateResolved = "resolved"
	// placeStateUnresolved — место заведено, координат нет: видно списком,
	// но не точкой. Рабочее состояние, а не ошибка (см. PlacesMigration).
	placeStateUnresolved = "unresolved"
	// placeStateMissing — корпуса нет в справочнике (слой пар).
	placeStateMissing = "missing"
	// placeStateNoBuilding — строка аудитории корпуса не называет: «без ауд.»,
	// просто «201» (слой пар).
	placeStateNoBuilding = "no_building"
	// placeStateSeveral — одна пара назвала два корпуса: точку выбрать нельзя
	// ни на один (слой пар).
	placeStateSeveral = "several"
	// placeStateNoPlace — событие ни к какому месту не привязано (слой
	// событий). Отличается от missing: там корпус назван, но его нет в
	// справочнике, здесь человек места не выбирал вовсе.
	placeStateNoPlace = "no_place"
	// placeStateNoDate — у события нет даты: встать в период оно не может,
	// но и исчезнуть из ответа не имеет права (слой событий).
	placeStateNoDate = "no_date"
)

// mapPlace — координаты места на карте. Отдельная маленькая структура, а не
// store.Place: слоям нужны три поля, а id, автор и время правки — внутренность
// справочника, и привязывать к ним формат карты значит менять её ради того,
// что в справочнике просто поменяли порядок колонок.
//
// Ссылка на неё nil, когда точки нет. Нолем это выразить нельзя: 0 —
// правдоподобная координата (западная Африка), и подставить её вместо
// неизвестного значило бы нарисовать корпус там, где его никогда не было.
type mapPlace struct {
	Name string  `json:"name"`
	Lat  float64 `json:"lat"`
	Lon  float64 `json:"lon"`
}
