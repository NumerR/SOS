package apeks

import "context"

// Backend — доступ к источнику официального расписания.
//
// Реализации две, и выбирают они одно и то же:
//
//   - Client — запрос к эндпоинту и разбор ответа кодом этого репозитория
//     (internal/apeks/parser.go, порт parser.py);
//   - Python — тот же разбор приложенным Python-парсером: сервер запускает
//     tools/schedule-parser/fetch.py как отдельный процесс и читает его JSON.
//
// Интерфейс появился потому, что у владельца есть рабочий парсер на Python, и
// переписывать его на Go не требуется — см. docs/05-DECISIONS.md, ADR-0021.
// До этого у поля Handlers.Apeks был конкретный тип, и обоснование тоже
// было в комментариях: второму реализатору незачем существовать. Он появился,
// поэтому список методов здесь минимальный: ровно то, что спрашивает
// обработчик импорта, плюс адрес источника для лога старта.
//
// Что interface не меняет: токен по-прежнему держит сервер и ни одна из
// реализаций не отдаёт его наружу — ни в текстах ошибок, ни в аргументах
// запущенного процесса. Права на импорт тоже остаются у обработчиков:
// ни Client, ни Python не знают про сессии и CSRF.
type Backend interface {
	// GetGroups — каталог групп источника (инфраструктура: ~587 записей).
	GetGroups(ctx context.Context) ([]Group, error)

	// GetMonth — пары одной группы за один месяц, уже разобранные.
	GetMonth(ctx context.Context, groupID string, month, year int) (*Month, error)

	// Endpoint — адрес, куда идёт запрос. Нужен честному логу старта:
	// печатать константу, когда оператор сменил адрес переменной окружения,
	// значит соврать в журнале именно там, где конфигурацию и отлаживают.
	Endpoint() string

	// Engine — каким кодом разобран ответ: "go" или "python". Попадает в
	// админский статус источника, чтобы привезённое расписание можно было
	// соотнести с парсером, который его принёс.
	Engine() string
}
