package apeks

import "strings"

// Номера корпусов из строки аудитории.
//
// Почему это правило живёт здесь, а не в слое карты: строка `room` — текст
// источника, и единственный, кто знает его формат, — разбор ответа АПЭКС
// (ADR-0021). Перенести выделение корпуса в обработчик или в SQL значило бы
// иметь вторую копию формата, расходящуюся с первой молча, — ровно то, из-за
// чего пары уже однажды стали разбирать при импорте, а не при каждой загрузке
// страницы.
//
// Формат взят из импортированных данных, а не из документации источника
// (26 различных строк на ноябрь 2026):
//
//	к. 3/306          — корпус 3, аудитория 306
//	к. 1/с/з          — корпус 1, «с/з»: черта внутри номера аудитории есть
//	к. 1/710, к. 1/711 — две аудитории в одном корпусе
//	без ауд.          — корпуса нет вовсе
//
// Последний случай — не данные, которые можно «додумать»: бриф (п.3)
// запрещает вымышленные координаты, поэтому пара без корпуса остаётся в
// неотмеченных, а не переезжает в ближайший дом.

// BuildingsFromRoom — номера корпусов, упомянутых в строке аудитории, в порядке
// появления и без повторов.
//
// Возвращает срез, а не одну строку, потому что «несколько корпусов в одной
// паре» — не ошибка разбора, а факт источника: два разных ответа означают
// «поставить точку» и «сказать, что место неизвестно». Вызывающий обязан
// различать len==1 от len>1, а не брать первый элемент.
func BuildingsFromRoom(room string) []string {
	text := strings.ToLower(room)

	var buildings []string
	seen := make(map[string]bool, 2)

	for at := 0; ; {
		found := strings.Index(text[at:], "к.")
		if found < 0 {
			return buildings
		}

		// Индекс относительно всей строки, а не остатка: иначе второй токен
		// («к. 1/710, к. 1/711») искался бы от начала, и цикл не продвигался.
		start := at + found + len("к.")
		value, next := buildingDigits(text, start)
		if value != "" && !seen[value] {
			seen[value] = true
			buildings = append(buildings, value)
		}

		at = start + next
		if at > len(text) {
			return buildings
		}
	}
}

// buildingDigits читает номер корпуса после «к.»: пробелы, затем цифры до
// нецифры (обычно косой черты). Возвращает номер и сколько символов съедено,
// считая и пробелы, и сам номер.
//
// Цифры берутся как есть, без «01» → «1»: справочник мест ведёт человек по тем
// же строкам источника, и нормализация на одной стороне сделала бы пару
// «в справочнике есть, на карте её нет» необъяснимой. Расхождение обязано
// остаться в неотмеченных — оно и есть сигнал, что справочник пора поправить.
func buildingDigits(text string, at int) (string, int) {
	read := at
	for read < len(text) && (text[read] == ' ' || text[read] == '\t' || text[read] == '-') {
		read++
	}

	from := read
	for read < len(text) && text[read] >= '0' && text[read] <= '9' {
		read++
	}

	return text[from:read], read - at
}
